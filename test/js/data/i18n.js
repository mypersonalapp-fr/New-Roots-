// The Roots — traductions des MENUS de l'application (pas du contenu des
// leçons, qui reste dans la langue apprise — voir lessons.html). Chaque
// écran importe `t` et lit `store.get().settings.interfaceLang` pour savoir
// quelle langue utiliser, puis appelle `t("cle", lang)` ou
// `t("cle", lang, { nom: valeur })` pour une chaîne avec un mot à remplacer.
//
// Portée volontairement limitée aux menus/textes d'interface (comme prévu
// dans Paramètres > Langue de l'interface > "Menus de l'application") :
// le test de niveau garde ses questions en français (tester l'anglais dans
// une autre langue d'interface n'aurait pas de sens pour les questions
// elles-mêmes), et lessons.html (le contenu des leçons) n'est pas concerné.

export const LANG_NAMES = {
  en: { fr: "Anglais", en: "English", es: "Inglés", pt: "Inglês" },
  es: { fr: "Espagnol", en: "Spanish", es: "Español", pt: "Espanhol" },
  pt: { fr: "Portugais", en: "Portuguese", es: "Portugués", pt: "Português" },
};

export const VARIANT_NAMES = {
  "en-gb": { fr: "Britannique", en: "British", es: "Británico", pt: "Britânico" },
  "en-us": { fr: "Américain", en: "American", es: "Americano", pt: "Americano" },
  "es-co": { fr: "Colombien", en: "Colombian", es: "Colombiano", pt: "Colombiano" },
  "es-es": { fr: "Espagne", en: "Spain", es: "España", pt: "Espanha" },
  "pt-br": { fr: "Brésilien", en: "Brazilian", es: "Brasileño", pt: "Brasileiro" },
  "pt-pt": { fr: "Europe", en: "European", es: "Europeo", pt: "Europeu" },
};

export function langName(code, lang) {
  const row = LANG_NAMES[code];
  if (!row) return code;
  return row[lang] || row.fr;
}

export function variantName(code, lang) {
  const row = VARIANT_NAMES[code];
  if (!row) return code;
  return row[lang] || row.fr;
}

const LOCALE_MAP = { fr: "fr-FR", en: "en-GB", es: "es-ES", pt: "pt-PT" };

export function formatDate(iso, lang) {
  if (!iso) return "";
  try {
    return new Intl.DateTimeFormat(LOCALE_MAP[lang] || "fr-FR", {
      day: "numeric", month: "long", year: "numeric",
    }).format(new Date(iso));
  } catch (e) { return ""; }
}

